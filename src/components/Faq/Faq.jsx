function FaqCard({ question, answer }) {
  const [open, setOpen] = useState(false);

  return (
    <article className={open ? 'faq-card is-open' : 'faq-card'}>
      <button type="button" aria-expanded={open} onClick={() => setOpen(!open)}>
        <span>{question}</span>
        <i aria-hidden="true">+</i>
      </button>
      <div className="faq-card__answer">
        <div>{answer.map((paragraph) => <p key={paragraph}>{paragraph}</p>)}</div>
      </div>
    </article>
  );
}

export function Faq() {
  const midpoint = Math.ceil(items.length / 2);

  return (
    <section className="faq" id="faq">
      <header>
        <h2>Часто задаваемые вопросы</h2>
        <p>Ответы, которые помогут вам принять решение уверенно — без рисков для бренда и безопасности</p>
      </header>
      <div className="faq__columns">
        <div>{items.slice(0, midpoint).map(([question, answer]) => <FaqCard question={question} answer={answer} key={question} />)}</div>
        <div>{items.slice(midpoint).map(([question, answer]) => <FaqCard question={question} answer={answer} key={question} />)}</div>
      </div>
    </section>
  );
}
